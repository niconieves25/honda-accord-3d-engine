import {presentationCss} from './presentation.mjs';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
const project=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const teardown=process.env.TEARDOWN_SKILL_DIR||path.join(os.homedir(),'.claude/skills/teardown');
const {fromDeps}=await import(pathToFileURL(path.join(teardown,'paths.mjs')));
const mediaManifest=path.join(project,'anatomy-media/f22a6/manifest.json');
const englishManifest=path.join(project,'anatomy-media/f22a6/en/manifest.json');
const mediaHash=createHash('sha256');
for(const file of [mediaManifest,englishManifest])if(fs.existsSync(file))mediaHash.update(fs.readFileSync(file));
const mediaRevision=mediaHash.digest('hex').slice(0,16);
const result=await fromDeps('esbuild').build({entryPoints:[path.join(project,'anatomy-app/main.js')],bundle:true,minify:true,format:'esm',write:false,target:'es2022',nodePaths:[path.join(teardown,'node_modules')],define:{__ANATOMY_MEDIA_REVISION__:JSON.stringify(mediaRevision)},legalComments:'none'});
const js=result.outputFiles[0].text.replace(/<\/script/gi,'<\\/script');
const css=presentationCss('anatomy-app');
const html=`<!doctype html><html lang="es"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="description" content="Honda F22A6 1993 EX 5MT: catálogo de piezas 3D y videos · 3D component catalogue and videos · Español / English."><title>Anatomía del Honda F22A6</title><style>${css}</style></head><body><div id="app"></div><script type="module">${js}</script></body></html>`;
fs.writeFileSync(path.join(project,'anatomy.html'),html);
console.log(`Built anatomy.html · ${(Buffer.byteLength(html)/1024).toFixed(0)} KB`);
